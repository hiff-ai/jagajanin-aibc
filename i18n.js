let LANG = 'id';
function t(key, vars = {}) {
  // Danger-sign findings reuse the checklist label: f_sign_bleeding → sign_bleeding.
  if (key.startsWith('f_sign_') && !(key in STRINGS[LANG]) && !(key in STRINGS.id)) key = key.slice(2);
  const s = STRINGS[LANG][key] ?? STRINGS.id[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
